"use client";

import * as React from "react";
import {
  useState,
  useEffect,
  forwardRef,
  useImperativeHandle,
  useRef,
} from "react";
import { useTheme } from "next-themes";
import { toast } from "sonner";
import Uppy, { UppyFile, Meta } from "@uppy/core";
import Dashboard from "@uppy/dashboard";
import GoogleDrive from "@uppy/google-drive";
import Url from "@uppy/url";
import AwsS3Multipart from "@uppy/aws-s3";
import { sanitizeAndUniquifyFilename } from "@/lib/utils/sanitize-filename";

// Import Uppy styles and our custom theme
import "@uppy/core/dist/style.min.css";
import "@uppy/dashboard/dist/style.min.css";
import "@/app/uppy-theme.css";

import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { CheckCircle2, AlertCircle } from "lucide-react";
import {
  validateFileWithDuckDb,
  ValidationResult,
  detectFileFormat,
  SUPPORTED_FORMATS,
  SupportedFileFormat,
} from "@/lib/validation/validate-file";
import { useDuckDb } from "@/hooks/useDuckDb";
import { useColumnNameStore } from "@/lib/stores/columnNameStore";
import { useColumnDescriptionStore } from "@/lib/stores/columnDescriptionStore";
import { useUploadStore } from "@/lib/stores/uploadStore";

export interface UnifiedUploaderProps {
  projectId: string;
  onUploadSuccess?: (
    file: UppyFile<Meta, Record<string, never>>,
    response: unknown,
    validation: ValidationResult
  ) => void;
  onUploadError?: (error: string) => void;
  onAutoGenerateDescriptions?: (
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    summary: Record<string, any>,
    rows: string[][]
  ) => Promise<void>;
  onValidationSuccess?: () => void;
}

export interface UnifiedUploaderRef {
  triggerUpload: (datasetName: string, description: string) => Promise<void>;
  clearUploader: () => void;
}

function getFileFormatDisplay(format: SupportedFileFormat): string {
  const formatNames = {
    csv: "CSV",
    parquet: "Parquet",
    json: "JSON",
    excel: "Excel",
    duckdb: "DuckDB",
  };
  return formatNames[format] || format.toUpperCase();
}

export const UnifiedUploader = forwardRef<
  UnifiedUploaderRef,
  UnifiedUploaderProps
>(function UnifiedUploader(
  {
    projectId: _projectId,
    onUploadSuccess,
    onAutoGenerateDescriptions,
    onValidationSuccess,
    onUploadError,
  },
  ref
) {
  // Theme hook
  const { resolvedTheme } = useTheme();

  // Uppy instance state
  const [uppy, setUppy] = useState<Uppy | null>(null);
  const [selectedFile, setSelectedFile] = useState<UppyFile<
    Meta,
    Record<string, never>
  > | null>(null);
  const [isUploading, setIsUploading] = useState(false);
  const [uploadProgress, setUploadProgress] = useState(0);
  const [uploadError, setUploadError] = useState<string | null>(null);
  const [validationResult, setValidationResult] =
    useState<ValidationResult | null>(null);
  const dashboardRef = React.useRef<HTMLDivElement>(null);

  // DuckDB hook
  const { db, isInitialized, error: duckDbError } = useDuckDb();

  // Store hooks - create stable references to prevent re-renders
  const setUploadedFileRef = useRef(useUploadStore.getState().setUploadedFile);
  const setValidationResultStoreRef = useRef(
    useUploadStore.getState().setValidationResult
  );
  const setUploadResponseRef = useRef(
    useUploadStore.getState().setUploadResponse
  );
  const setOriginalFileNameRef = useRef(
    useUploadStore.getState().setOriginalFileName
  );
  const setDetectedFormatRef = useRef(
    useUploadStore.getState().setDetectedFormat
  );

  // Column store hooks - create stable references
  const setColumnMappingsRef = useRef(
    useColumnNameStore.getState().setColumnMappings
  );
  const resetColumnMappingsRef = useRef(
    useColumnNameStore.getState().resetColumnMappings
  );
  const clearColumnDescriptionsRef = useRef(
    useColumnDescriptionStore.getState().clearColumnDescriptions
  );

  // Create stable callback references to prevent useEffect re-runs
  const onAutoGenerateDescriptionsRef = useRef(onAutoGenerateDescriptions);
  const onValidationSuccessRef = useRef(onValidationSuccess);
  const onUploadSuccessRef = useRef(onUploadSuccess);
  const onUploadErrorRef = useRef(onUploadError);

  // Create a ref for validation result to avoid stale closures
  const validationResultRef = useRef(validationResult);

  // Update refs when props change
  React.useEffect(() => {
    onAutoGenerateDescriptionsRef.current = onAutoGenerateDescriptions;
    onValidationSuccessRef.current = onValidationSuccess;
    onUploadSuccessRef.current = onUploadSuccess;
    onUploadErrorRef.current = onUploadError;
    validationResultRef.current = validationResult;
  }, [
    onAutoGenerateDescriptions,
    onValidationSuccess,
    onUploadSuccess,
    onUploadError,
    validationResult,
  ]);

  // Expose upload functionality via ref
  useImperativeHandle(ref, () => ({
    triggerUpload: async (_datasetName: string, _description: string) => {
      if (!uppy || !selectedFile) {
        throw new Error("No file selected");
      }
      await handleUpload();
    },
    clearUploader: () => {
      if (uppy) {
        // Clear all files from Uppy
        uppy.cancelAll();
        const files = uppy.getFiles();
        files.forEach((file) => {
          uppy.removeFile(file.id);
        });
      }
      // Clear local state
      setSelectedFile(null);
      setValidationResult(null);
      setUploadError(null);
      setUploadProgress(0);
      setIsUploading(false);

      // Clear store state
      resetColumnMappingsRef.current();
      clearColumnDescriptionsRef.current();
    },
  }));

  // Initialize Uppy with all plugins
  useEffect(() => {
    if (!dashboardRef.current) return;

    const companionUrl =
      process.env.NEXT_PUBLIC_COMPANION_URL || "http://localhost:3020";

    // Get max upload size from environment variable, default to 100GB (100000MB)
    const maxUploadSizeMB = parseInt(process.env.NEXT_PUBLIC_MAX_UPLOAD_SIZE_MB || "100000", 10);
    const maxUploadSizeBytes = maxUploadSizeMB * 1000 * 1000; // Convert MB to bytes

    const uppyInstance = new Uppy({
      id: "unified-uploader",
      allowMultipleUploads: false,
      restrictions: {
        maxFileSize: maxUploadSizeBytes,
        maxNumberOfFiles: 1,
        allowedFileTypes: [
          ".csv",
          ".parquet",
          ".json",
          ".xlsx",
          ".xls",
          ".duckdb",
          "text/csv",
          "application/json",
          "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
          "application/vnd.ms-excel",
        ],
      },
      debug: process.env.NODE_ENV === "development",
            onBeforeFileAdded: (currentFile) => {
                setOriginalFileNameRef.current(currentFile.name || "");
                const originalName = currentFile?.name || '';
                const modifiedName = sanitizeAndUniquifyFilename(originalName);
      
                const modifiedFile = {
                    ...currentFile,
                    name: modifiedName, // Update the primary name
                    meta: {
                        ...currentFile.meta,
                        name: modifiedName, // Also update meta name if needed by plugins
                        originalName: originalName, // Store original name in meta if needed later
                    },
                };
                return modifiedFile;
            }
    });

    // Add Dashboard plugin with proper theme
    uppyInstance.use(Dashboard, {
      target: dashboardRef.current,
      inline: true,
      width: "100%",
      height: 500,
      showProgressDetails: true,
      hideUploadButton: true, // Hide upload button - we'll handle upload manually in step 4
      hideRetryButton: false,
      hidePauseResumeButton: false,
      hideCancelButton: false,
      showSelectedFiles: true,
      showRemoveButtonAfterComplete: false,
      proudlyDisplayPoweredByUppy: false,
      note: "Select files, import from URL, or choose from Google Drive",
      theme: resolvedTheme === "dark" ? "dark" : "light",
      doneButtonHandler: null,
    });

    // Add Google Drive plugin
    uppyInstance.use(GoogleDrive, {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      target: Dashboard as any,
      companionUrl,
      companionHeaders: {},
      companionCookiesRule: "same-origin",
    });

    // Add URL plugin
    uppyInstance.use(Url, {
      // eslint-disable-next-line @typescript-eslint/no-explicit-any
      target: Dashboard as any,
      companionUrl,
      companionHeaders: {},
      companionCookiesRule: "same-origin",
    });

    // Add AWS S3 Multipart plugin for final upload
    uppyInstance.use(AwsS3Multipart, {
      endpoint: companionUrl,
      // shouldUseMultipart: true,
    });

    // Handle file selection
    uppyInstance.on("file-added", async (file) => {
      try {
        setSelectedFile(file);
        setUploadError(null);

        // Detect file format
        const format = detectFileFormat(
          file.name || "",
          file.type || "application/octet-stream"
        );

        if (!format) {
          const supportedFormats = Object.keys(SUPPORTED_FORMATS).join(", ");
          const errorMsg = `Unsupported file format. Supported formats: ${supportedFormats}`;
          setUploadError(errorMsg);
          toast.error(errorMsg);
          return;
        }

        setDetectedFormatRef.current(format);

        // Validate file if DuckDB is initialized
        if (isInitialized && db && file.data) {
          try {
            // Convert the file data to ArrayBuffer for validation
            let buffer: ArrayBuffer;
            if (file.data instanceof ArrayBuffer) {
              buffer = file.data;
            } else if (file.data instanceof Blob) {
              buffer = await file.data.arrayBuffer();
            } else {
              // For files from URL or Google Drive, we may not have the data yet
              // Create a basic validation result for files without immediate data
              const basicResult: ValidationResult = {
                isValid: true,
                format,
                columnNames: [],
                columnTypes: [],
                previewData: [],
              };
              setValidationResult(basicResult);
              setValidationResultStoreRef.current(basicResult);
              setUploadedFileRef.current(file);

              // Call validation success callback for consistency
              if (onValidationSuccessRef.current) {
                onValidationSuccessRef.current();
              }
              return;
            }

            const result = await validateFileWithDuckDb(
              db,
              buffer,
              file.name || "",
              file.size || 0,
              file.type || "application/octet-stream"
            );

            setValidationResult(result);
            setValidationResultStoreRef.current(result);

            if (result.isValid) {
              toast.success(
                `${getFileFormatDisplay(format)} validation successful!`
              );

              if (result.columnNames) {
                setColumnMappingsRef.current(
                  result.columnNames,
                  result.columnTypes
                );
              }

              // Store file in upload store
              setUploadedFileRef.current(file);

              // Auto-generate descriptions if callback is provided
              if (onAutoGenerateDescriptionsRef.current && result.previewData) {
                const summary = {
                  columns: result.columnNames || [],
                  rowCount: result.previewRowCount || 0,
                };
                await onAutoGenerateDescriptionsRef.current(
                  summary,
                  result.previewData as string[][]
                );
              }

              // Call validation success callback
              if (onValidationSuccessRef.current) {
                onValidationSuccessRef.current();
              }
            } else {
              toast.error(
                `${getFileFormatDisplay(format)} validation failed: ${
                  result.error
                }`
              );
              // Store the file anyway so it can be used in the wizard
              setUploadedFileRef.current(file);
            }
          } catch (error) {
            const errorMessage =
              error instanceof Error ? error.message : "Validation failed";
            setUploadError(errorMessage);
            toast.error(errorMessage);
            // Store the file anyway so it can be used in the wizard
            setUploadedFileRef.current(file);
          }
        } else {
          // If DuckDB not available, create a basic validation result
          const basicResult: ValidationResult = {
            isValid: true,
            format,
            columnNames: [],
            columnTypes: [],
            previewData: [],
          };
          setValidationResult(basicResult);
          setValidationResultStoreRef.current(basicResult);
          setUploadedFileRef.current(file);

          // Call validation success callback
          if (onValidationSuccessRef.current) {
            onValidationSuccessRef.current();
          }
        }
      } catch (error) {
        // Catch any unexpected errors in the file-added handler
        const errorMessage =
          error instanceof Error
            ? error.message
            : "Unexpected error during file processing";
        setUploadError(errorMessage);
        toast.error(`File processing error: ${errorMessage}`);

        // Even if there's an error, try to store the file so it doesn't get lost
        try {
          setUploadedFileRef.current(file);
        } catch {
          // Silently ignore store errors
        }
      }
    });

    // Handle file removal
    uppyInstance.on("file-removed", (file) => {
      if (selectedFile?.id === file?.id) {
        setSelectedFile(null);
        setValidationResult(null);
        setUploadError(null);
        resetColumnMappingsRef.current();
        clearColumnDescriptionsRef.current();
      } else {
      }
    });

    // Handle upload progress
    uppyInstance.on("upload-progress", (file, progress) => {
      const bytesTotal = progress.bytesTotal || 0;
      if (bytesTotal > 0) {
        setUploadProgress(
          Math.round((progress.bytesUploaded / bytesTotal) * 100)
        );
      }
    });

    // Handle upload start
    uppyInstance.on("upload", () => {
      setIsUploading(true);
    });

    // Handle upload success
    uppyInstance.on("upload-success", async (file, response) => {
      try {
        setUploadResponseRef.current(response);

        // Use the current validation result from the ref to avoid stale closure
        if (onUploadSuccessRef.current && file && validationResultRef.current) {
          onUploadSuccessRef.current(
            file,
            response,
            validationResultRef.current
          );
        }

        toast.success("File uploaded successfully!");
        setIsUploading(false);
        setUploadProgress(0);
      } catch (error) {
        const errorMessage =
          error instanceof Error ? error.message : "Unknown error";
        setUploadError(`Upload success handler failed: ${errorMessage}`);
        toast.error(`Upload success handler failed: ${errorMessage}`);
      }
    });

    // Handle upload error
    uppyInstance.on("upload-error", (file, error) => {
      setUploadError(error.message);
      toast.error(`Upload failed: ${error.message}`);
      setIsUploading(false);
      if (onUploadErrorRef.current) {
        onUploadErrorRef.current(error.message);
      }
    });

    // Handle complete event
    uppyInstance.on("complete", (_result) => {
      setIsUploading(false);
    });

    // Handle restriction failures that might cause auto-removal
    uppyInstance.on("restriction-failed", (file, error) => {
      setUploadError(`File restriction failed: ${error.message}`);
      toast.error(`File restriction failed: ${error.message}`);
    });

    // Handle info events for debugging
    uppyInstance.on("info-visible", () => {
      // Debug information - currently not used
    });

    // Handle warning events
    uppyInstance.on("info-hidden", () => {});

    setUppy(uppyInstance);

    return () => {
      uppyInstance.destroy();
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [
    isInitialized,
    db,
    // CRITICAL: Removed ALL callback dependencies that change on every render
    // These callback props and store setters are causing the useEffect to re-run
    // and destroy/recreate the Uppy instance, which removes the files

    // Intentionally excluded: resolvedTheme, selectedFile?.id, validationResult
    // - resolvedTheme is handled by a separate useEffect to avoid Uppy recreation
    // - selectedFile?.id and validationResult use refs to avoid stale closures

    // Removed: onAutoGenerateDescriptions, onValidationSuccess, onUploadSuccess, onUploadError
    // Removed: setUploadedFile, setValidationResultStore, setUploadResponse,
    // Removed: setOriginalFileName, setDetectedFormat, setColumnMappings,
    // Removed: resetColumnMappings, clearColumnDescriptions
  ]);

  // Handle theme changes dynamically without recreating Uppy instance
  useEffect(() => {
    if (uppy && dashboardRef.current) {
      const dashboard = uppy.getPlugin("Dashboard") as Dashboard<
        Meta,
        Record<string, never>
      >;
      if (dashboard) {
        // Update the dashboard theme by updating the options
        dashboard.setOptions({
          theme: resolvedTheme === "dark" ? "dark" : "light",
        });

        // Force update the dashboard container class to trigger CSS changes
        const dashboardContainer =
          dashboardRef.current.querySelector(".uppy-Dashboard");
        if (dashboardContainer) {
          // Remove existing theme classes
          dashboardContainer.classList.remove(
            "uppy-theme-dark",
            "uppy-theme-light"
          );
          // Add the current theme class
          dashboardContainer.classList.add(
            `uppy-theme-${resolvedTheme === "dark" ? "dark" : "light"}`
          );
        }
      }
    }
  }, [uppy, resolvedTheme]);

  const handleUpload = async () => {
    if (!uppy || !selectedFile) return;

    try {
      await uppy.upload();
    } catch (error) {
      const errorMessage =
        error instanceof Error ? error.message : "Upload failed";
      setUploadError(errorMessage);
      toast.error(errorMessage);
    }
  };

  return (
    <div className="space-y-4">
      {uploadError && (
        <Alert variant="destructive">
          <AlertCircle className="h-4 w-4" />
          <AlertTitle>Upload Error</AlertTitle>
          <AlertDescription>{uploadError}</AlertDescription>
        </Alert>
      )}

      {duckDbError && (
        <Alert variant="destructive">
          <AlertCircle className="h-4 w-4" />
          <AlertTitle>DuckDB Error</AlertTitle>
          <AlertDescription>
            File validation unavailable: {String(duckDbError)}
          </AlertDescription>
        </Alert>
      )}

      {/* Validation Result */}
      {validationResult && validationResult.isValid && (
        <Alert className="bg-green-50 dark:bg-green-950/30 border-green-200 dark:border-green-900">
          <CheckCircle2 className="h-4 w-4 text-green-600 dark:text-green-400" />
          <AlertTitle className="text-green-800 dark:text-green-200">
            File Validation Successful
          </AlertTitle>
          <AlertDescription className="text-green-700 dark:text-green-300">
            {validationResult.format?.toUpperCase()} file is valid with{" "}
            {validationResult.columnNames?.length || 0} columns
          </AlertDescription>
        </Alert>
      )}

      {/* Uppy Dashboard */}
      <div className="border rounded-lg overflow-hidden bg-card">
        <div
          ref={dashboardRef}
          className={`uppy-theme-wrapper ${
            resolvedTheme === "dark" ? "uppy-theme-dark" : "uppy-theme-light"
          }`}
        />
      </div>

      {/* Upload Progress */}
      {isUploading && (
        <div className="space-y-2">
          <div className="flex justify-between text-sm">
            <span>Uploading to S3...</span>
            <span>{uploadProgress}%</span>
          </div>
          <div className="w-full bg-muted rounded-full h-2">
            <div
              className="bg-primary h-2 rounded-full transition-all duration-300"
              style={{ width: `${uploadProgress}%` }}
            />
          </div>
        </div>
      )}
    </div>
  );
});

UnifiedUploader.displayName = "UnifiedUploader";
