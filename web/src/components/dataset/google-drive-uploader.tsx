"use client";

import * as React from "react";
import { useState, useEffect, forwardRef, useImperativeHandle } from "react";
import { toast } from "sonner";
import Uppy, { UppyFile, Meta } from "@uppy/core";
import GoogleDrive from "@uppy/google-drive";
import Dashboard from "@uppy/dashboard";
import AwsS3 from "@uppy/aws-s3";

// Import Dashboard CSS
import "@uppy/core/dist/style.min.css";
import "@uppy/dashboard/dist/style.min.css";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { 
  CheckCircle2, 
  AlertCircle
} from "lucide-react";
import {
  validateFileWithDuckDb,
  ValidationResult,
  detectFileFormat,
  SUPPORTED_FORMATS,
  SupportedFileFormat,
} from "@/lib/validation/validate-file";
import { useDuckDb } from "@/hooks/useDuckDb";
import { useColumnNameStore } from "@/lib/stores/columnNameStore";
import { useColumnDescriptionStore } from "@/lib/stores/columnDescriptionStore";
import { useUploadStore } from "@/lib/stores/uploadStore";

export interface GoogleDriveUploaderProps {
  projectId: string;
  onUploadSuccess?: (
    file: UppyFile<Meta, Record<string, never>>,
    response: unknown,
    validation: ValidationResult
  ) => void;
  onUploadError?: (error: string) => void;
  onAutoGenerateDescriptions?: (
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    summary: Record<string, any>,
    rows: string[][]
  ) => Promise<void>;
  onValidationSuccess?: () => void;
}

export interface GoogleDriveUploaderRef {
  triggerUpload: (datasetName: string, description: string) => Promise<void>;
}

function getFileFormatDisplay(format: SupportedFileFormat): string {
  const formatNames = {
    csv: "CSV",
    parquet: "Parquet", 
    json: "JSON",
    excel: "Excel",
    duckdb: "DuckDB",
  };
  return formatNames[format] || format.toUpperCase();
}

export const GoogleDriveUploader = forwardRef<GoogleDriveUploaderRef, GoogleDriveUploaderProps>(
  function GoogleDriveUploader({
    projectId: _projectId,
    onUploadSuccess,
    onAutoGenerateDescriptions,
    onValidationSuccess,
    onUploadError,
  }, ref) {
    // Uppy instance state
    const [uppy, setUppy] = useState<Uppy | null>(null);
    const [selectedFile, setSelectedFile] = useState<UppyFile<Meta, Record<string, never>> | null>(null);
    const [isUploading, setIsUploading] = useState(false);
    const [uploadProgress, setUploadProgress] = useState(0);
    const [uploadError, setUploadError] = useState<string | null>(null);
    const [validationResult, setValidationResult] = useState<ValidationResult | null>(null);
    const [_showDashboard, _setShowDashboard] = useState(false);
    const dashboardRef = React.useRef<HTMLDivElement>(null);

    // DuckDB hook
    const { db, isInitialized, error: duckDbError } = useDuckDb();

    // Store hooks
    const setUploadedFile = useUploadStore((state) => state.setUploadedFile);
    const setValidationResultStore = useUploadStore((state) => state.setValidationResult);
    const setUploadResponse = useUploadStore((state) => state.setUploadResponse);
    const setOriginalFileName = useUploadStore((state) => state.setOriginalFileName);
    const setDetectedFormat = useUploadStore((state) => state.setDetectedFormat);

    // Column store hooks
    const setColumnMappings = useColumnNameStore((state) => state.setColumnMappings);
    const _resetColumnMappings = useColumnNameStore((state) => state.resetColumnMappings);
    const _clearColumnDescriptions = useColumnDescriptionStore((state) => state.clearColumnDescriptions);

    // Expose upload functionality via ref
    useImperativeHandle(ref, () => ({
      triggerUpload: async (_datasetName: string, _description: string) => {
        if (!uppy || !selectedFile) {
          throw new Error('No file selected from Google Drive');
        }
        await handleUpload();
      }
    }));

    // Initialize Uppy with Google Drive plugin
    useEffect(() => {
      if (!dashboardRef.current) return;

      const companionUrl = process.env.NEXT_PUBLIC_COMPANION_URL || "http://localhost:3020";
      
      const uppyInstance = new Uppy({
        id: 'googledrive-uploader',
        allowMultipleUploads: false,
        restrictions: {
          maxFileSize: 1000 * 1000 * 1000, // 1GB limit
          maxNumberOfFiles: 1,
          allowedFileTypes: [
            '.csv', '.parquet', '.json', '.xlsx', '.xls', '.duckdb',
            'text/csv', 'application/json', 
            'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            'application/vnd.ms-excel'
          ],
        },
      });

      // Add Dashboard plugin
      uppyInstance.use(Dashboard, {
        target: dashboardRef.current,
        inline: true,
        width: '100%',
        height: 400,
        showProgressDetails: true,
        hideUploadButton: false,
        hideRetryButton: false,
        hidePauseResumeButton: false,
        hideCancelButton: false,
        showSelectedFiles: true,
        showRemoveButtonAfterComplete: false,
        note: 'Select files from Google Drive',
      });

      // Add Google Drive plugin
      uppyInstance.use(GoogleDrive, {
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        target: Dashboard as any,
        companionUrl,
        companionHeaders: {},
        companionCookiesRule: 'same-origin',
      });

      // Add AWS S3 plugin for final upload
      uppyInstance.use(AwsS3, {
        endpoint: companionUrl,
      });

      // Handle file selection from Google Drive
      uppyInstance.on('file-added', async (file) => {
        console.log('File selected from Google Drive:', file.name);
        setSelectedFile(file);
        setUploadError(null);
        setOriginalFileName(file.name || '');

        // Detect file format
        const format = detectFileFormat(file.name || '', file.type || 'application/octet-stream');
        
        if (!format) {
          const supportedFormats = Object.keys(SUPPORTED_FORMATS).join(", ");
          const errorMsg = `Unsupported file format. Supported formats: ${supportedFormats}`;
          setUploadError(errorMsg);
          toast.error(errorMsg);
          return;
        }

        setDetectedFormat(format);

        // Validate file if DuckDB is initialized
        if (isInitialized && db && file.data) {
          try {
            // Convert the file data to ArrayBuffer for validation
            let buffer: ArrayBuffer;
            if (file.data instanceof ArrayBuffer) {
              buffer = file.data;
            } else if (file.data instanceof Blob) {
              buffer = await file.data.arrayBuffer();
            } else {
              throw new Error('Unsupported file data type');
            }

            const result = await validateFileWithDuckDb(
              db,
              buffer,
              file.name || '',
              file.size || 0,
              file.type || 'application/octet-stream'
            );

            setValidationResult(result);
            setValidationResultStore(result);

            if (result.isValid) {
              toast.success(`${getFileFormatDisplay(format)} validation successful!`);
              
              if (result.columnNames) {
                setColumnMappings(result.columnNames, result.columnTypes);
              }

              // Store file in upload store
              setUploadedFile(file);

              // Auto-generate descriptions if callback is provided
              if (onAutoGenerateDescriptions && result.previewData) {
                const summary = {
                  columns: result.columnNames || [],
                  rowCount: result.previewRowCount || 0,
                };
                await onAutoGenerateDescriptions(summary, result.previewData as string[][]);
              }

              // Call validation success callback
              if (onValidationSuccess) {
                onValidationSuccess();
              }
            } else {
              toast.error(`${getFileFormatDisplay(format)} validation failed: ${result.error}`);
            }
          } catch (error) {
            const errorMessage = error instanceof Error ? error.message : 'Validation failed';
            setUploadError(errorMessage);
            toast.error(errorMessage);
          }
        } else {
          // If DuckDB not available, create a basic validation result
          const basicResult: ValidationResult = {
            isValid: true,
            format,
            columnNames: [],
            columnTypes: [],
            previewData: []
          };
          setValidationResult(basicResult);
          setValidationResultStore(basicResult);
          setUploadedFile(file);
        }
      });

      // Handle upload progress
      uppyInstance.on('upload-progress', (file, progress) => {
        const bytesTotal = progress.bytesTotal || 0;
        if (bytesTotal > 0) {
          setUploadProgress(Math.round((progress.bytesUploaded / bytesTotal) * 100));
        }
      });

      // Handle upload start
      uppyInstance.on('upload', () => {
        setIsUploading(true);
      });

      // Handle upload success
      uppyInstance.on('upload-success', async (file, response) => {
        try {
          setUploadResponse(response);
          
          if (onUploadSuccess && file && validationResult) {
            onUploadSuccess(file, response, validationResult);
          }

          toast.success("File uploaded from Google Drive successfully!");
          setIsUploading(false);
          setUploadProgress(0);
        } catch (error) {
          const errorMessage = error instanceof Error ? error.message : "Unknown error";
          setUploadError(`Upload success handler failed: ${errorMessage}`);
          toast.error(`Upload success handler failed: ${errorMessage}`);
        }
      });

      // Handle upload error
      uppyInstance.on('upload-error', (file, error) => {
        setUploadError(error.message);
        toast.error(`Upload failed: ${error.message}`);
        setIsUploading(false);
        if (onUploadError) {
          onUploadError(error.message);
        }
      });

      setUppy(uppyInstance);

      return () => {
        uppyInstance.destroy();
      };
    }, [
      isInitialized, 
      db, 
      onAutoGenerateDescriptions, 
      onValidationSuccess, 
      onUploadSuccess, 
      onUploadError,
      setUploadedFile,
      setValidationResultStore,
      setUploadResponse,
      setOriginalFileName,
      setDetectedFormat,
      setColumnMappings,
      validationResult
    ]);

    const handleUpload = async () => {
      if (!uppy || !selectedFile) return;

      try {
        await uppy.upload();
      } catch (error) {
        const errorMessage = error instanceof Error ? error.message : 'Upload failed';
        setUploadError(errorMessage);
        toast.error(errorMessage);
      }
    };


    return (
      <div className="space-y-4">
        {uploadError && (
          <Alert variant="destructive">
            <AlertCircle className="h-4 w-4" />
            <AlertTitle>Google Drive Upload Error</AlertTitle>
            <AlertDescription>{uploadError}</AlertDescription>
          </Alert>
        )}

        {duckDbError && (
          <Alert variant="destructive">
            <AlertCircle className="h-4 w-4" />
            <AlertTitle>DuckDB Error</AlertTitle>
            <AlertDescription>
              File validation unavailable: {String(duckDbError)}
            </AlertDescription>
          </Alert>
        )}

        {/* Validation Result */}
        {validationResult && validationResult.isValid && (
          <Alert className="bg-green-50 dark:bg-green-950/30 border-green-200 dark:border-green-900">
            <CheckCircle2 className="h-4 w-4 text-green-600 dark:text-green-400" />
            <AlertTitle className="text-green-800 dark:text-green-200">
              File Validation Successful
            </AlertTitle>
            <AlertDescription className="text-green-700 dark:text-green-300">
              {validationResult.format?.toUpperCase()} file is valid with{" "}
              {validationResult.columnNames?.length || 0} columns
            </AlertDescription>
          </Alert>
        )}

        {/* Uppy Dashboard with Google Drive */}
        <div className="border rounded-lg overflow-hidden">
          <div ref={dashboardRef} />
        </div>

        {/* Upload Progress */}
        {isUploading && (
          <div className="space-y-2">
            <div className="flex justify-between text-sm">
              <span>Uploading to S3...</span>
              <span>{uploadProgress}%</span>
            </div>
            <div className="w-full bg-muted rounded-full h-2">
              <div
                className="bg-primary h-2 rounded-full transition-all duration-300"
                style={{ width: `${uploadProgress}%` }}
              />
            </div>
          </div>
        )}
      </div>
    );
  }
);

GoogleDriveUploader.displayName = "GoogleDriveUploader";